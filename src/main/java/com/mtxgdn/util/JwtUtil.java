package com.mtxgdn.util;

import io.jsonwebtoken.Claims;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.SignatureAlgorithm;
import io.jsonwebtoken.security.Keys;

import javax.crypto.SecretKey;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.Date;

public class JwtUtil {

    /** 密钥最小长度（字节数）— HMAC-SHA256 至少需要 256 位 = 32 字节 */
    private static final int MIN_KEY_BYTES = 32;

    private static volatile SecretKey SECRET_KEY;

    /** 是否由安装向导自动生成（重启后失效警告） */
    private static volatile boolean autoGenerated = false;

    /** Token 有效期：7 天 */
    private static final long EXPIRATION_MS = 7 * 24 * 60 * 60 * 1000L;

    /**
     * 初始化密钥。
     * <ul>
     *   <li>优先读取 jwt.secret 配置</li>
     *   <li>配置为空且 isInstallMode=false 时，拒绝启动并抛出异常</li>
     *   <li>isInstallMode=true 时（安装向导阶段），自动生成临时密钥</li>
     * </ul>
     *
     * @param isInstallMode 是否处于安装模式（首次启动未配置jwt.secret时）
     */
    public static synchronized void init(boolean isInstallMode) {
        String configured = AppConfig.get("jwt.secret");

        if (configured != null && !configured.isBlank()) {
            byte[] keyBytes = configured.getBytes(java.nio.charset.StandardCharsets.UTF_8);
            if (keyBytes.length < MIN_KEY_BYTES) {
                throw new RuntimeException(
                    "[JwtUtil] jwt.secret 长度不足！需要至少 " + MIN_KEY_BYTES + " 字节（" + (MIN_KEY_BYTES * 8) + " 位），" +
                    "当前 " + keyBytes.length + " 字节。请在 config/application.yml 中设置足够长的密钥。");
            }
            SECRET_KEY = Keys.hmacShaKeyFor(keyBytes);
            autoGenerated = false;
            System.out.println("[JwtUtil] ✓ JWT 密钥已从配置加载");
            return;
        }

        // 未配置密钥
        if (!isInstallMode) {
            // 非安装模式 — 拒绝启动
            throw new RuntimeException(
                "[JwtUtil] jwt.secret 未配置！请通过安装向导完成配置，或在 config/application.yml 中手动设置 jwt.secret。");
        }

        // 安装模式 — 自动生成临时密钥（安装向导会写入配置文件，重启后加载正式密钥）
        byte[] randomBytes = new byte[48];
        new SecureRandom().nextBytes(randomBytes);
        SECRET_KEY = Keys.hmacShaKeyFor(randomBytes);
        autoGenerated = true;
        System.err.println("[JwtUtil] ⚠ 安装模式：已生成临时 JWT 密钥。安装向导将写入正式密钥，重启后生效。");
    }

    /**
     * 启动后校验：如果密钥仍是自动生成的，发出强警告。
     * 建议在 Main.doMain() 服务器启动完成后调用。
     */
    public static void warnIfAutoGenerated() {
        if (autoGenerated) {
            System.err.println("============================================================");
            System.err.println("[JwtUtil] ⚠ 严重安全警告：JWT 密钥为自动生成的临时密钥！");
            System.err.println("[JwtUtil]   重启后所有玩家 Token 将失效，请尽快完成安装向导。");
            System.err.println("============================================================");
        }
    }

    /**
     * 检查密钥是否已正确配置（非自动生成）。
     * @return true 表示密钥已由用户配置
     */
    public static boolean isKeyConfigured() {
        return SECRET_KEY != null && !autoGenerated;
    }

    /**
     * 获取当前密钥的安全指纹（前8字符的Base64），用于状态显示。
     * 不暴露完整密钥。
     */
    public static String getKeyFingerprint() {
        if (SECRET_KEY == null) return "未初始化";
        byte[] encoded = SECRET_KEY.getEncoded();
        String b64 = Base64.getEncoder().encodeToString(encoded);
        return b64.substring(0, Math.min(8, b64.length())) + "...";
    }

    /** 强制重新加载密钥（安装完成后重启时调用） */
    public static synchronized void reload() {
        SECRET_KEY = null;
        autoGenerated = false;
        init(false);
    }

    // ==================== Token 操作 ====================

    public static String generateToken(Long userId, String username) {
        ensureKey();
        Date now = new Date();
        Date expiration = new Date(now.getTime() + EXPIRATION_MS);

        return Jwts.builder()
                .setSubject(String.valueOf(userId))
                .claim("username", username)
                .setIssuedAt(now)
                .setExpiration(expiration)
                .signWith(SECRET_KEY, SignatureAlgorithm.HS256)
                .compact();
    }

    public static boolean validateToken(String token) {
        if (token == null || token.isBlank()) return false;
        ensureKey();
        try {
            Jwts.parserBuilder()
                    .setSigningKey(SECRET_KEY)
                    .build()
                    .parseClaimsJws(token);
            return true;
        } catch (Exception e) {
            return false;
        }
    }

    public static Long extractUserId(String token) {
        ensureKey();
        Claims claims = Jwts.parserBuilder()
                .setSigningKey(SECRET_KEY)
                .build()
                .parseClaimsJws(token)
                .getBody();
        return Long.parseLong(claims.getSubject());
    }

    public static String extractUsername(String token) {
        ensureKey();
        Claims claims = Jwts.parserBuilder()
                .setSigningKey(SECRET_KEY)
                .build()
                .parseClaimsJws(token)
                .getBody();
        return claims.get("username", String.class);
    }

    /**
     * 解析 token 的过期时间，供 {@link TokenBlacklist} 精确决定吊销记录保留多久。
     *
     * @return 过期时间；token 非法、签名错误或缺少 exp 时返回 {@code null}
     */
    public static Date extractExpiration(String token) {
        if (token == null || token.isBlank()) {
            return null;
        }
        ensureKey();
        try {
            Claims claims = Jwts.parserBuilder()
                    .setSigningKey(SECRET_KEY)
                    .build()
                    .parseClaimsJws(token)
                    .getBody();
            return claims.getExpiration();
        } catch (Exception e) {
            return null;
        }
    }

    private static void ensureKey() {
        if (SECRET_KEY == null) {
            throw new IllegalStateException("[JwtUtil] 密钥未初始化，请先调用 init()");
        }
    }
}
